class VentaM {
    private int codigo;
    private String fecha;
    private int cantidad;

    public VentaM(int cod,String fe,int cant) {
        codigo=codigo;
        fecha=fe;
        cantidad=cant;
    }

    public int getCodigo() {
        return codigo;
    }
    public String getFecha() {
        return fecha;
    }
    public int getCantidad() {
        return cantidad;
    }
}
